// Package version — сведения о сборке. Взят из wsldrive.
//
// Значения подставляются на сборке через -ldflags, поэтому в исходном коде
// стоят те, что соответствуют сборке «на коленке»: без сценария сборки версия
// честно объявляет себя неизвестной, а не выдаёт себя за выпуск.
package version

import (
	"fmt"
	"runtime"
)

// Number — номер выпуска вида 0.1.<номер сборки>-alpha.
//
// Номером сборки служит число снимков в хранилище (git rev-list --count HEAD).
// Выбор объясняется тем, что счётчик в файле пришлось бы либо хранить в
// хранилище и разрешать столкновения при слиянии, либо держать местным, и
// тогда один и тот же номер означал бы у разных людей разное. Число снимков
// же одинаково у всех, растёт монотонно и ничего не требует.
var Number = "0.1.0-alpha"

// Commit — снимок, из которого собрано.
var Commit = "неизвестно"

// Built — время сборки.
var Built = "неизвестно"

// Dirty сообщает, что сборка сделана из изменённого дерева и потому в точности
// не воспроизводима.
var Dirty = "no"

// String — однострочное описание для журнала и ключа -version.
func String(program string) string {
	s := fmt.Sprintf("%s %s (снимок %s, собрано %s, %s/%s, %s)",
		program, Number, Commit, Built, runtime.GOOS, runtime.GOARCH, runtime.Version())
	if Dirty == "yes" {
		s += " [изменённое дерево]"
	}
	return s
}
